#!/usr/bin/env python3
"""Export normalized migration rows as reviewable SQL for Cloudflare D1."""

from __future__ import annotations

import argparse
import sqlite3
from pathlib import Path
from typing import Any


NORMALIZED_TABLES = (
    "circle_spaces",
    "members",
    "member_tags",
    "member_space_access",
    "member_profiles",
    "member_email_preferences",
    "member_entitlements",
)

RAW_TABLES = (
    "circle_import_batches",
    "circle_raw_members",
    "circle_raw_spaces",
    "circle_raw_posts",
    "circle_raw_comments",
    "circle_raw_events",
)

COURSE_TABLES = (
    "courses",
    "course_modules",
    "course_lessons",
    "course_progress",
    "course_notes",
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", required=True, help="Imported SQLite database.")
    parser.add_argument("--out", required=True, help="SQL file to write.")
    parser.add_argument(
        "--include-raw",
        action="store_true",
        help="Include raw Circle rows and source JSON (contains additional personal data).",
    )
    parser.add_argument(
        "--include-courses",
        action="store_true",
        help="Include optional course tables, including private learner notes and progress.",
    )
    parser.add_argument(
        "--replace",
        action="store_true",
        help="Use INSERT OR REPLACE. This can trigger cascades; default is the safer INSERT OR IGNORE.",
    )
    args = parser.parse_args()

    db_path = Path(args.db).expanduser().resolve()
    output_path = Path(args.out).expanduser().resolve()
    if not db_path.is_file():
        raise SystemExit(f"Database not found: {db_path}")
    if output_path == db_path:
        raise SystemExit("Output path must be different from the SQLite database.")

    # Source mappings reference both import batches and normalized members.
    tables = (*RAW_TABLES, *NORMALIZED_TABLES, "member_import_sources") if args.include_raw else NORMALIZED_TABLES
    if args.include_courses:
        tables = (*tables, *COURSE_TABLES)
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        statements, counts = build_statements(conn, tables, replace=args.replace)
    finally:
        conn.close()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    header = [
        "-- Generated by scripts/export_d1_sql.py.",
        "-- Review this file as sensitive data before loading it into D1.",
        "PRAGMA foreign_keys = ON;",
        "-- D1 imports must not contain explicit BEGIN/COMMIT transaction wrappers.",
    ]
    output_path.write_text("\n".join([*header, *statements]) + "\n", encoding="utf-8")

    print(f"SQL export: {output_path}")
    for table, count in counts.items():
        print(f"{table}: {count}")


def build_statements(
    conn: sqlite3.Connection,
    tables: tuple[str, ...],
    *,
    replace: bool,
) -> tuple[list[str], dict[str, int]]:
    statements: list[str] = []
    counts: dict[str, int] = {}
    for table in tables:
        if not table_exists(conn, table):
            continue
        columns = [row["name"] for row in conn.execute(f'PRAGMA table_info("{table}")')]
        rows = list(conn.execute(f'SELECT * FROM "{table}"'))
        counts[table] = len(rows)
        if not rows:
            continue
        quoted_columns = ", ".join(f'"{column}"' for column in columns)
        statements.append(f"-- {table}: {len(rows)} row(s)")
        insert_verb = "INSERT OR REPLACE" if replace else "INSERT OR IGNORE"
        for row in rows:
            values = ", ".join(sql_literal(row[column]) for column in columns)
            statements.append(
                f'{insert_verb} INTO "{table}" ({quoted_columns}) VALUES ({values});'
            )
    return statements, counts


def table_exists(conn: sqlite3.Connection, table: str) -> bool:
    return bool(
        conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?",
            (table,),
        ).fetchone()
    )


def sql_literal(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bytes):
        return "X'" + value.hex() + "'"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


if __name__ == "__main__":
    main()
